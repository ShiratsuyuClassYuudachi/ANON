/** 总菜单同时用作加好友、入群欢迎语，始终保留帮助入口。 */
export function qqHelpMenu(group: boolean): string {
  return [
    'ANON 机器人帮助',
    group ? '群内请先 @我，再发送以下指令。' : '私聊直接发送以下指令；群内请先 @我。',
    '帮助 绑定：个人账号、群内身份、项目群与通知',
    '帮助 待办：发任务描述直接创建，可 @成员指派',
    '帮助 报名：发节目资料，预览确认后进入待审核',
    '帮助 记账：发单笔人民币收支，核对后确认保存',
    '帮助 物料：开始上传物料 → 发文件 → 结束上传物料',
    '帮助 导出：合并转发，或开始导出 → 结束导出',
    '发送「帮助」「菜单」或 /help 返回总菜单。查看帮助不会取消正在进行的操作，也不会延长草稿有效期。',
    ...(!aiConfigured() ? ['当前未启用 AI，待办、报名和文字记账暂不可用；绑定、物料和导出仍可使用。'] : []),
  ].join('\n');
}

/** 只消费独立的纯文本帮助指令，避免截获转发记录、引用和附件说明。 */
export function qqHelpReply(d: QqMessage): string | null {
  if ((d.message_type ?? 0) !== 0 || d.attachments?.length) return null;
  const content = qqMessageText(d);
  const match = content?.match(/^(?:帮助|菜单|\/?help)(?:\s+(.+))?$/i);
  if (!match) return null;
  const topic = match[1]?.trim();
  if (!topic) return qqHelpMenu(!!d.group_openid);
  if (!Object.prototype.hasOwnProperty.call(TOPICS, topic)) return `未找到该帮助主题，请选择菜单中的主题。\n\n${qqHelpMenu(!!d.group_openid)}`;
  return `${TOPICS[topic]}\n\n发送「帮助」返回总菜单。查看帮助不会取消当前操作。`;
}
